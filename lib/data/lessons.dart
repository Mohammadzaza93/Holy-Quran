/// الحصول على درس بالترتيب
Lesson? getLessonByOrder(int order) {
  try {
    return tajweedLessons.firstWhere((l) => l.order == order);
  } catch (_) {
    return null;
  }
}

/// الحصول على درس بالمعرّف
Lesson? getLessonById(String id) {
  try {
    return tajweedLessons.firstWhere((l) => l.id == id);
  } catch (_) {
    return null;
  }
}
